package scratch;

public class PlayWithRotates {

	public static void main(String[] args) {
		int i = 1 << 0;
		int j = 1 << 1;
		int k = 1 << 2;
		
		System.out.println("i = " + i);
		System.out.println("j = " + j);
		System.out.println("k = " + k);
		
		System.out.print( (1 << 3) + "\n" + (1 << 4) );
	}
}
